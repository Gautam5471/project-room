// Synthetic room only: orientation must preserve writing and make no room writes.
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, rmSync } from 'node:fs';
import { chromium } from 'playwright';
import { createResultsFixture } from './results-fixture.mjs';
import { createRoomServer } from '../server/http.mjs';
import { EVENT_TYPES as T } from '../src/events.js';
import { signInFixture } from './auth-signin.mjs';
import { ensureSidebarOpen, ensureSidebarClosed } from './room-chrome.mjs';

for (const mobile of [false, true]) test(`room overview ${mobile ? 'mobile' : 'desktop'}: source-backed orientation preserves writing and updates live`, { timeout: 25000 }, async t => {
  const f = createResultsFixture(), server = createRoomServer({ store: f.store, streamInterval: 40 });
  f.send('owner', T.CHANNEL_CREATED, { channelId: 'planning', name: 'planning' });
  f.send('owner', T.MESSAGE_POSTED, { messageId: 'planning-note', channelId: 'planning', body: 'The launch plan.' });
  f.send('owner', T.DECISION_RECORDED, { sourceMessageId: 'planning-note', statement: 'Ship a small, useful first version.' });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); server.closeStreams(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); f.store.close(); rmSync(f.directory, { recursive: true, force: true }); });
  const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(6000);
  const errors = [], outside = [], writes = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => { if (new URL(route.request().url()).origin !== origin) { outside.push(route.request().url()); return route.abort(); } return route.continue(); });
  await page.goto(origin); await signInFixture(page, f.keys.owner); await page.locator('#main').waitFor();
  page.on('request', r => { if (r.method() !== 'GET' && new URL(r.url()).pathname.startsWith('/api/rooms/')) writes.push(r.url()); });
  await page.locator('#message-input').fill('Keep this room draft');
  const open = async () => { await ensureSidebarOpen(page); await page.locator('#room-overview-open').click(); };
  await open();
  const dialog = page.locator('#room-overview-dialog');
  assert.match(await page.locator('#room-overview-purpose').textContent(), /Synthetic acceptance/);
  assert.match(await dialog.textContent(), /Ship a small, useful first version/);
  assert.match(await dialog.textContent(), /Active work/);
  f.send('owner', T.ROOM_CHARTER_UPDATED, { expectedRevision: 0, purpose: 'Current shared purpose', outputs: null, boundaries: null, escalation: null });
  await page.waitForFunction(() => document.querySelector('#room-overview-purpose').textContent === 'Current shared purpose');
  assert.equal(await dialog.locator('[data-open-work="native-result"]').count(), 1);
  const section = heading => dialog.locator('section').filter({ has: page.locator('h3', { hasText: heading }) });
  assert.equal(await section('Recent results').locator('[data-open-work="pending-result"]').count(), 0, 'unverified completion is not presented as a finished result');
  assert.equal(await section(/^Active work/).locator('[data-open-work="pending-result"]').count(), 1, 'a result still waiting on review stays visible as active work');
  assert.equal(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  mkdirSync('test-results/room-overview', { recursive: true });
  await page.screenshot({ path: `test-results/room-overview/${mobile ? 'mobile' : 'desktop'}.png` });
  await dialog.locator('[data-open-message="planning-note"]').click();
  await dialog.waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.activeElement?.dataset.messageRecordId === 'planning-note');
  assert.equal(await page.locator('#conversation-title').textContent(), '# planning');
  assert.equal(await page.locator('#message-input').inputValue(), '', 'opening another channel never carries the general draft into its composer');
  await ensureSidebarOpen(page);
  await page.locator('#channel-list [data-channel="general"]').click();
  await ensureSidebarClosed(page);
  assert.equal(await page.locator('#message-input').inputValue(), 'Keep this room draft', 'the exact original draft remains in its original channel');
  assert.equal(await page.locator('#main').evaluate(node => node.classList.contains('sidebar-open')), false);
  await open();
  f.reopen('native-result');
  await page.waitForFunction(() => {
    const sections = [...document.querySelectorAll('#room-overview-content section')];
    const results = sections.find(s => s.querySelector('h3')?.textContent === 'Recent results');
    return !results?.querySelector('[data-open-work="native-result"]');
  });
  assert.match(await dialog.textContent(), /Launch checklist/);
  const conversationUrl = page.url();
  await dialog.locator('[data-open-work="approved-result"]').click();
  await page.waitForFunction(() => document.activeElement?.dataset.workRecordId === 'approved-result');
  assert.equal(await page.locator('#message-input').inputValue(), 'Keep this room draft');
  await page.getByRole('button', { name: 'Back to conversation', exact: true }).click();
  await page.waitForURL(conversationUrl);
  assert.equal(await page.locator('#message-input').inputValue(), 'Keep this room draft', 'return navigation preserves the original conversation draft');
  await open(); await page.locator('#room-overview-close').click();
  await page.waitForFunction(() => document.querySelector('#room-overview-open') === document.activeElement);
  assert.equal(await page.locator('#room-overview-open').evaluate(node => node === document.activeElement), true);
  await open();
  f.store.issueAccessKey('commons', 'owner');
  await page.locator('#auth-panel').waitFor({ state: 'visible' });
  assert.equal(await dialog.isVisible(), false);
  assert.equal(await page.locator('#room-overview-content').textContent(), '');
  assert.equal(await page.locator('#room-overview-purpose').textContent(), '');
  assert.equal(await page.locator('#room-overview-title').textContent(), 'Room overview');
  assert.deepEqual(errors, []); assert.deepEqual(outside, []); assert.deepEqual(writes.filter(url => !url.endsWith("/typing")), []);
});
